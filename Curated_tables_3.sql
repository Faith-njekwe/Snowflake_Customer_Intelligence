CREATE OR REPLACE TABLE CURATED.ITEM AS

WITH deduped AS (
    SELECT *
    FROM RAW.ITEM
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY I_ITEM_SK
        ORDER BY LOAD_DATE DESC
    ) = 1
)

SELECT

    /* Keys */
    CAST(I_ITEM_SK AS NUMBER)            AS ITEM_SK,
    I_ITEM_ID                            AS ITEM_ID,

    /* Dates */
    TRY_TO_DATE(I_REC_START_DATE)        AS REC_START_DATE,
    TRY_TO_DATE(I_REC_END_DATE)          AS REC_END_DATE,

    /* Item Details */
    TRIM(I_ITEM_DESC)                    AS ITEM_DESC,

    ROUND(COALESCE(I_CURRENT_PRICE,0),2)   AS CURRENT_PRICE,
    ROUND(COALESCE(I_WHOLESALE_COST,0),2)  AS WHOLESALE_COST,

    CAST(I_BRAND_ID AS NUMBER)           AS BRAND_ID,
    TRIM(I_BRAND)                        AS BRAND,

    CAST(I_CLASS_ID AS NUMBER)           AS CLASS_ID,
    TRIM(I_CLASS)                        AS CLASS,

    CAST(I_CATEGORY_ID AS NUMBER)        AS CATEGORY_ID,
    TRIM(I_CATEGORY)                     AS CATEGORY,

    CAST(I_MANUFACT_ID AS NUMBER)        AS MANUFACT_ID,
    TRIM(I_MANUFACT)                     AS MANUFACT,

    NULLIF(TRIM(I_SIZE),'N/A')           AS SIZE,
    NULLIF(TRIM(I_FORMULATION),'N/A')    AS FORMULATION,
    NULLIF(TRIM(I_COLOR),'N/A')          AS COLOR,
    NULLIF(TRIM(I_UNITS),'N/A')          AS UNITS,
    NULLIF(TRIM(I_CONTAINER),'Unknown')  AS CONTAINER,

    CAST(COALESCE(I_MANAGER_ID,0) AS NUMBER) AS MANAGER_ID,

    TRIM(I_PRODUCT_NAME)                 AS PRODUCT_NAME,

    LOAD_ID,
    LOAD_DATE,
    BATCH_ID

FROM deduped

WHERE COALESCE(I_ITEM_SK,0) > 0
  AND COALESCE(I_CURRENT_PRICE,0) >= 0
  AND COALESCE(I_WHOLESALE_COST,0) >= 0;

