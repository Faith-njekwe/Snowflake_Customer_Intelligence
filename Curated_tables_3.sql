-- marketing domain curated
CREATE OR REPLACE TABLE CURATED.PROMOTION AS

WITH deduped AS (
    SELECT *
    FROM RAW.PROMOTION
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY P_PROMO_SK
        ORDER BY LOAD_DATE DESC
    ) = 1
)

SELECT

    CAST(P_PROMO_SK AS NUMBER)          AS PROMO_SK,
    P_PROMO_ID                          AS PROMO_ID,

    CAST(P_START_DATE_SK AS NUMBER)     AS START_DATE_SK,
    CAST(P_END_DATE_SK AS NUMBER)       AS END_DATE_SK,
    CAST(P_ITEM_SK AS NUMBER)           AS ITEM_SK,

    ROUND(COALESCE(P_COST,0),2)         AS COST,
    COALESCE(P_RESPONSE_TARGET,0)       AS RESPONSE_TARGET,

    TRIM(P_PROMO_NAME)                  AS PROMO_NAME,

    COALESCE(P_CHANNEL_DMAIL,'N')       AS CHANNEL_DMAIL,
    COALESCE(P_CHANNEL_EMAIL,'N')       AS CHANNEL_EMAIL,
    COALESCE(P_CHANNEL_CATALOG,'N')     AS CHANNEL_CATALOG,
    COALESCE(P_CHANNEL_TV,'N')          AS CHANNEL_TV,
    COALESCE(P_CHANNEL_RADIO,'N')       AS CHANNEL_RADIO,
    COALESCE(P_CHANNEL_PRESS,'N')       AS CHANNEL_PRESS,
    COALESCE(P_CHANNEL_EVENT,'N')       AS CHANNEL_EVENT,
    COALESCE(P_CHANNEL_DEMO,'N')        AS CHANNEL_DEMO,

    TRIM(P_CHANNEL_DETAILS)             AS CHANNEL_DETAILS,
    TRIM(P_PURPOSE)                     AS PURPOSE,

    COALESCE(P_DISCOUNT_ACTIVE,'N')     AS DISCOUNT_ACTIVE,

    LOAD_ID,
    LOAD_DATE,
    BATCH_ID

FROM deduped

WHERE COALESCE(P_PROMO_SK,0) > 0;

