    FROM RAW.WEB_SITE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY WEB_SITE_SK
        ORDER BY LOAD_DATE DESC
    ) = 1
)

SELECT

    CAST(WEB_SITE_SK AS NUMBER)         AS WEB_SITE_SK,
    WEB_SITE_ID                         AS WEB_SITE_ID,

    TRY_TO_DATE(WEB_REC_START_DATE)     AS REC_START_DATE,
    TRY_TO_DATE(WEB_REC_END_DATE)       AS REC_END_DATE,

    CAST(WEB_OPEN_DATE_SK AS NUMBER)    AS OPEN_DATE_SK,
    CAST(WEB_CLOSE_DATE_SK AS NUMBER)   AS CLOSE_DATE_SK,

    TRIM(WEB_NAME)                      AS WEB_NAME,
    TRIM(WEB_CLASS)                     AS WEB_CLASS,
    TRIM(WEB_MANAGER)                   AS WEB_MANAGER,

    COALESCE(WEB_MKT_ID,0)              AS WEB_MKT_ID,
    TRIM(WEB_MKT_CLASS)                 AS WEB_MKT_CLASS,
    TRIM(WEB_MKT_DESC)                  AS WEB_MKT_DESC,
    TRIM(WEB_MARKET_MANAGER)            AS WEB_MARKET_MANAGER,

    COALESCE(WEB_COMPANY_ID,0)          AS COMPANY_ID,
    TRIM(WEB_COMPANY_NAME)              AS COMPANY_NAME,

    TRIM(WEB_STREET_NUMBER)             AS STREET_NUMBER,
    TRIM(WEB_STREET_NAME)               AS STREET_NAME,
    TRIM(WEB_STREET_TYPE)               AS STREET_TYPE,
    TRIM(WEB_SUITE_NUMBER)              AS SUITE_NUMBER,

    INITCAP(TRIM(WEB_CITY))             AS CITY,
    INITCAP(TRIM(WEB_COUNTY))           AS COUNTY,
    UPPER(TRIM(WEB_STATE))              AS STATE,
    TRIM(WEB_ZIP)                       AS ZIP,
    INITCAP(TRIM(WEB_COUNTRY))          AS COUNTRY,

    ROUND(COALESCE(WEB_GMT_OFFSET,0),2)     AS GMT_OFFSET,
    ROUND(COALESCE(WEB_TAX_PERCENTAGE,0),2) AS TAX_PERCENTAGE,

    LOAD_ID,
    LOAD_DATE,
    BATCH_ID

FROM deduped

WHERE COALESCE(WEB_SITE_SK,0) > 0;

