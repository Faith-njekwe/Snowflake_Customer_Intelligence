from promotion;

CREATE OR REPLACE TABLE CURATED.WEB_PAGE AS

WITH deduped AS (
    SELECT *
    FROM RAW.WEB_PAGE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY WP_WEB_PAGE_SK
        ORDER BY LOAD_DATE DESC
    ) = 1
)

SELECT

    CAST(WP_WEB_PAGE_SK AS NUMBER)        AS WEB_PAGE_SK,
    WP_WEB_PAGE_ID                        AS WEB_PAGE_ID,

    CAST(WP_CREATION_DATE_SK AS NUMBER)   AS CREATION_DATE_SK,
    CAST(WP_ACCESS_DATE_SK AS NUMBER)     AS ACCESS_DATE_SK,

    TRY_TO_DATE(WP_REC_START_DATE)        AS REC_START_DATE,
    TRY_TO_DATE(WP_REC_END_DATE)          AS REC_END_DATE,

    COALESCE(WP_AUTOGEN_FLAG,'N')         AS AUTOGEN_FLAG,

    CAST(WP_CUSTOMER_SK AS NUMBER)        AS CUSTOMER_SK,

    LOWER(TRIM(WP_URL))                   AS URL,
    LOWER(TRIM(WP_TYPE))                  AS PAGE_TYPE,

    COALESCE(WP_CHAR_COUNT,0)             AS CHAR_COUNT,
    COALESCE(WP_LINK_COUNT,0)             AS LINK_COUNT,
    COALESCE(WP_IMAGE_COUNT,0)            AS IMAGE_COUNT,
    COALESCE(WP_MAX_AD_COUNT,0)           AS MAX_AD_COUNT,

    LOAD_ID,
    LOAD_DATE,
    BATCH_ID

FROM deduped

WHERE COALESCE(WP_WEB_PAGE_SK,0) > 0
  AND COALESCE(WP_CHAR_COUNT,0) >= 0
  AND COALESCE(WP_LINK_COUNT,0) >= 0
  AND COALESCE(WP_IMAGE_COUNT,0) >= 0;

