CREATE OR REPLACE TABLE CURATED.CUSTOMER AS

SELECT *
FROM (

    SELECT

        /* Numeric conversions */
        TRY_TO_NUMBER(C_CUSTOMER_SK)          AS C_CUSTOMER_SK,
        TRIM(C_CUSTOMER_ID)                   AS C_CUSTOMER_ID,
        TRY_TO_NUMBER(C_CURRENT_CDEMO_SK)     AS C_CURRENT_CDEMO_SK,
        TRY_TO_NUMBER(C_CURRENT_HDEMO_SK)     AS C_CURRENT_HDEMO_SK,
        TRY_TO_NUMBER(C_CURRENT_ADDR_SK)      AS C_CURRENT_ADDR_SK,
        TRY_TO_NUMBER(C_FIRST_SHIPTO_DATE_SK) AS C_FIRST_SHIPTO_DATE_SK,
        TRY_TO_NUMBER(C_FIRST_SALES_DATE_SK)  AS C_FIRST_SALES_DATE_SK,

        /* Trim whitespace and standardise text */
        INITCAP(TRIM(C_SALUTATION))           AS C_SALUTATION,
        INITCAP(TRIM(C_FIRST_NAME))           AS C_FIRST_NAME,
        INITCAP(TRIM(C_LAST_NAME))            AS C_LAST_NAME,

        UPPER(TRIM(
            COALESCE(C_PREFERRED_CUST_FLAG,'N')
        )) AS C_PREFERRED_CUST_FLAG,

        /* Numeric birth attributes */
        TRY_TO_NUMBER(C_BIRTH_DAY)            AS C_BIRTH_DAY,
        TRY_TO_NUMBER(C_BIRTH_MONTH)          AS C_BIRTH_MONTH,
        TRY_TO_NUMBER(C_BIRTH_YEAR)           AS C_BIRTH_YEAR,

        INITCAP(TRIM(
            COALESCE(C_BIRTH_COUNTRY,'Unknown')
        )) AS C_BIRTH_COUNTRY,

        LOWER(TRIM(
            COALESCE(C_LOGIN,'unknown')
        )) AS C_LOGIN,

        LOWER(TRIM(
            COALESCE(C_EMAIL_ADDRESS,'unknown@example.com')
        )) AS C_EMAIL_ADDRESS,

        /* Date conversion */
        TRY_TO_DATE(C_LAST_REVIEW_DATE)       AS C_LAST_REVIEW_DATE,

        /* Derived business attributes */
        YEAR(CURRENT_DATE())
          - TRY_TO_NUMBER(C_BIRTH_YEAR)
          AS CUSTOMER_AGE,

        CASE
            WHEN TRY_TO_NUMBER(C_BIRTH_YEAR) IS NULL
                THEN 'Unknown'
            WHEN YEAR(CURRENT_DATE())
                 - TRY_TO_NUMBER(C_BIRTH_YEAR) < 25
                THEN 'Young Adult'
            WHEN YEAR(CURRENT_DATE())
                 - TRY_TO_NUMBER(C_BIRTH_YEAR) < 45
                THEN 'Adult'
            WHEN YEAR(CURRENT_DATE())
                 - TRY_TO_NUMBER(C_BIRTH_YEAR) < 65
                THEN 'Middle Aged'
            ELSE 'Senior'
        END AS AGE_GROUP,

        /* Audit metadata retained */
        LOAD_ID,
        LOAD_DATE,
        SOURCE_FILE_NAME,
        BATCH_ID,

        /* Duplicate detection */
        ROW_NUMBER() OVER (
            PARTITION BY C_CUSTOMER_ID
            ORDER BY LOAD_DATE DESC
        ) AS RN

    FROM RAW.RAW_CUSTOMER
)
WHERE C_CUSTOMER_ID NOT IN (
SELECT C_CUSTOMER_ID
FROM CURATED.INVALID_CUSTOMER
);


