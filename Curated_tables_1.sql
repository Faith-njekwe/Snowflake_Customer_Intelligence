CREATE OR REPLACE TABLE CURATED.CUSTOMER_ADDRESS AS
WITH DEDUPED AS (
    SELECT *,
           ROW_NUMBER() OVER (
               PARTITION BY CA_ADDRESS_SK
               ORDER BY LOAD_DATE DESC
           ) AS RN
    FROM RAW.raw_customer_address
)
SELECT
    CA_ADDRESS_SK,
    TRIM(CA_ADDRESS_ID) AS CA_ADDRESS_ID,

    -- add unknowns
    COALESCE(TRIM(CA_STREET_NUMBER), 'UNKNOWN') AS CA_STREET_NUMBER,
    UPPER(COALESCE(TRIM(CA_STREET_NAME), 'UNKNOWN')) AS CA_STREET_NAME,
    UPPER(COALESCE(TRIM(CA_STREET_TYPE), 'UNKNOWN')) AS CA_STREET_TYPE,
    COALESCE(TRIM(CA_SUITE_NUMBER), 'N/A') AS CA_SUITE_NUMBER,

    UPPER(COALESCE(TRIM(CA_CITY), 'UNKNOWN')) AS CA_CITY,
    UPPER(COALESCE(TRIM(CA_COUNTY), 'UNKNOWN')) AS CA_COUNTY,
    UPPER(COALESCE(TRIM(CA_STATE), 'UNKNOWN')) AS CA_STATE,
    TRIM(COALESCE(CA_ZIP, 'UNKNOWN')) AS CA_ZIP,
    UPPER(COALESCE(TRIM(CA_COUNTRY), 'UNKNOWN')) AS CA_COUNTRY,

    COALESCE(CA_GMT_OFFSET, 0) AS CA_GMT_OFFSET,

    UPPER(COALESCE(TRIM(CA_LOCATION_TYPE), 'UNKNOWN')) AS CA_LOCATION_TYPE,

   -- make regions
    CASE
        WHEN UPPER(CA_STATE) IN ('CA','OR','WA','AK','HI')
            THEN 'WEST'
        WHEN UPPER(CA_STATE) IN ('NY','NJ','MA','CT','RI','VT','NH','ME','PA')
            THEN 'EAST'
        WHEN UPPER(CA_STATE) IN ('TX','OK','FL','GA','AL','MS','LA','SC','NC','TN','KY','VA','WV','AR')
            THEN 'SOUTH'
        WHEN UPPER(CA_STATE) IN ('IL','IN','IA','KS','MI','MN','MO','NE','ND','OH','SD','WI')
            THEN 'MIDWEST'
        ELSE 'OTHER'
    END AS REGION,

    LOAD_ID,
    LOAD_DATE,
    SOURCE_FILE_NAME,
    BATCH_ID

FROM DEDUPED
WHERE RN = 1
  AND CA_ADDRESS_SK IS NOT NULL;


