-- CURATED.CUSTOMER_DEMOGRAPHICS
-- Purpose: Cleanse and standardise customer demographics

CREATE OR REPLACE TABLE CURATED.CUSTOMER_DEMOGRAPHICS AS

WITH DEDUPED AS (
    SELECT *,
           ROW_NUMBER() OVER (
               PARTITION BY CD_DEMO_SK
               ORDER BY LOAD_DATE DESC
           ) AS RN
    FROM raw_customer_demographics
)

SELECT

    -- Primary Key
    CD_DEMO_SK,

    -- Gender
    CASE
        WHEN UPPER(TRIM(CD_GENDER)) = 'M' THEN 'MALE'
        WHEN UPPER(TRIM(CD_GENDER)) = 'F' THEN 'FEMALE'
        ELSE 'UNKNOWN'
    END AS CD_GENDER,

    -- Marital Status
    CASE
        WHEN UPPER(TRIM(CD_MARITAL_STATUS)) = 'M' THEN 'MARRIED'
        WHEN UPPER(TRIM(CD_MARITAL_STATUS)) = 'S' THEN 'SINGLE'
        WHEN UPPER(TRIM(CD_MARITAL_STATUS)) = 'D' THEN 'DIVORCED'
        WHEN UPPER(TRIM(CD_MARITAL_STATUS)) = 'W' THEN 'WIDOWED'
        ELSE 'UNKNOWN'
    END AS CD_MARITAL_STATUS,

    -- Education
    UPPER(COALESCE(TRIM(CD_EDUCATION_STATUS), 'UNKNOWN'))
        AS CD_EDUCATION_STATUS,

    -- Purchase Estimate
    COALESCE(CD_PURCHASE_ESTIMATE, 0)
        AS CD_PURCHASE_ESTIMATE,

    -- Credit Rating
    UPPER(COALESCE(TRIM(CD_CREDIT_RATING), 'UNKNOWN'))
        AS CD_CREDIT_RATING,

    -- Dependents
    COALESCE(CD_DEP_COUNT, 0)
        AS CD_DEP_COUNT,

    COALESCE(CD_DEP_EMPLOYED_COUNT, 0)
        AS CD_DEP_EMPLOYED_COUNT,

    COALESCE(CD_DEP_COLLEGE_COUNT, 0)
        AS CD_DEP_COLLEGE_COUNT,


    -- Metadata
    LOAD_ID,
    LOAD_DATE,
    SOURCE_FILE_NAME,
    BATCH_ID

FROM DEDUPED
WHERE RN = 1
  AND CD_DEMO_SK IS NOT NULL;

