-- Create Curate WEB_SALES

CREATE OR REPLACE TABLE CURATED.WEB_SALES AS

WITH deduped AS (
    SELECT *
    FROM RAW.WEB_SALES
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY WS_ORDER_NUMBER, WS_ITEM_SK
        ORDER BY LOAD_DATE DESC
    ) = 1
)

SELECT

    /* Keys */
    CAST(WS_SOLD_DATE_SK       AS NUMBER) AS SOLD_DATE_SK,
    CAST(WS_SOLD_TIME_SK       AS NUMBER) AS SOLD_TIME_SK,
    CAST(WS_SHIP_DATE_SK       AS NUMBER) AS SHIP_DATE_SK,
    CAST(WS_ITEM_SK            AS NUMBER) AS ITEM_SK,

    CAST(WS_BILL_CUSTOMER_SK   AS NUMBER) AS BILL_CUSTOMER_SK,
    CAST(WS_SHIP_CUSTOMER_SK   AS NUMBER) AS SHIP_CUSTOMER_SK,

    CAST(WS_BILL_ADDR_SK       AS NUMBER) AS BILL_ADDR_SK,
    CAST(WS_SHIP_ADDR_SK       AS NUMBER) AS SHIP_ADDR_SK,

    CAST(WS_WEB_PAGE_SK        AS NUMBER) AS WEB_PAGE_SK,
    CAST(WS_WEB_SITE_SK        AS NUMBER) AS WEB_SITE_SK,
    CAST(WS_SHIP_MODE_SK       AS NUMBER) AS SHIP_MODE_SK,
    CAST(WS_WAREHOUSE_SK       AS NUMBER) AS WAREHOUSE_SK,
    CAST(WS_PROMO_SK           AS NUMBER) AS PROMO_SK,

    /* Order Information */
    CAST(WS_ORDER_NUMBER AS NUMBER) AS ORDER_NUMBER,

    /* Measures */
    COALESCE(WS_QUANTITY, 0) AS QUANTITY,

    ROUND(COALESCE(WS_WHOLESALE_COST, 0), 2) AS WHOLESALE_COST,
    ROUND(COALESCE(WS_LIST_PRICE, 0), 2) AS LIST_PRICE,
    ROUND(COALESCE(WS_SALES_PRICE, 0), 2) AS SALES_PRICE,

    ROUND(COALESCE(WS_EXT_DISCOUNT_AMT, 0), 2) AS EXT_DISCOUNT_AMT,
    ROUND(COALESCE(WS_EXT_SALES_PRICE, 0), 2) AS EXT_SALES_PRICE,
    ROUND(COALESCE(WS_EXT_WHOLESALE_COST, 0), 2) AS EXT_WHOLESALE_COST,
    ROUND(COALESCE(WS_EXT_LIST_PRICE, 0), 2) AS EXT_LIST_PRICE,
    ROUND(COALESCE(WS_EXT_TAX, 0), 2) AS EXT_TAX,
    ROUND(COALESCE(WS_COUPON_AMT, 0), 2) AS COUPON_AMT,
    ROUND(COALESCE(WS_EXT_SHIP_COST, 0), 2) AS EXT_SHIP_COST,

    ROUND(COALESCE(WS_NET_PAID, 0), 2) AS NET_PAID,
    ROUND(COALESCE(WS_NET_PAID_INC_TAX, 0), 2) AS NET_PAID_INC_TAX,
    ROUND(COALESCE(WS_NET_PAID_INC_SHIP, 0), 2) AS NET_PAID_INC_SHIP,
    ROUND(COALESCE(WS_NET_PAID_INC_SHIP_TAX, 0), 2) AS NET_PAID_INC_SHIP_TAX,
    ROUND(COALESCE(WS_NET_PROFIT, 0), 2) AS NET_PROFIT,

    /* Derived Classifications */

    CASE
        WHEN WS_QUANTITY <= 10 THEN 'Small Order'
        WHEN WS_QUANTITY <= 50 THEN 'Medium Order'
        ELSE 'Large Order'
    END AS ORDER_SIZE_BAND,

    CASE
        WHEN WS_NET_PROFIT < 0 THEN 'Loss'
        WHEN WS_NET_PROFIT < 1000 THEN 'Low Profit'
        ELSE 'High Profit'
    END AS PROFIT_BAND,

    CASE
        WHEN WS_COUPON_AMT > 0 THEN 'Coupon Used'
        ELSE 'No Coupon'
    END AS COUPON_USAGE,

    CASE
        WHEN WS_EXT_DISCOUNT_AMT > 0 THEN 'Discounted'
        ELSE 'Full Price'
    END AS DISCOUNT_TYPE,

    d.LOAD_ID,
    d.LOAD_DATE,
    d.BATCH_ID

FROM deduped d

INNER JOIN CURATED.CUSTOMER c
ON d.WS_BILL_CUSTOMER_SK = c.C_CUSTOMER_SK

WHERE COALESCE(d.WS_QUANTITY, 0) > 0
  AND COALESCE(d.WS_LIST_PRICE, 0) >= 0
  AND COALESCE(d.WS_SALES_PRICE, 0) >= 0;



