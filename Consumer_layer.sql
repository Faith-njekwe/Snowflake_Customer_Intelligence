CREATE OR REPLACE TABLE CONSUMER.RETURNS_INTELLIGENCE AS

WITH SALES_BASE AS (
    SELECT
        fs.ORDER_NUMBER,
        fs.CUSTOMER_KEY,
        fs.PRODUCT_KEY,

        MIN(fs.DATE_KEY) AS SALE_DATE_KEY,
        MIN(dd.D_DATE) AS SALE_DATE,

        SUM(fs.NET_PAID) AS SALES_VALUE,
        SUM(fs.NET_PROFIT) AS SALES_PROFIT,
        SUM(fs.QUANTITY) AS SALES_QUANTITY

    FROM MODELLED.FACT_SALES fs

    LEFT JOIN MODELLED.DIM_DATE dd
        ON fs.DATE_KEY = dd.D_DATE_SK

    GROUP BY
        fs.ORDER_NUMBER,
        fs.CUSTOMER_KEY,
        fs.PRODUCT_KEY
),

RETURNS_BASE AS (
    SELECT
        fr.RETURN_NUMBER,
        fr.CUSTOMER_KEY,
        fr.PRODUCT_KEY,

        fr.STORE_KEY,
        fr.REASON_KEY,
        fr.RETURN_CHANNEL,

        fr.DATE_KEY AS RETURN_DATE_KEY,
        dd.D_DATE AS RETURN_DATE,

        fr.RETURN_QUANTITY,
        fr.RETURN_AMT,
        fr.RETURN_TAX,
        fr.RETURN_AMT_INC_TAX,
        fr.FEE,
        fr.RETURN_SHIP_COST,
        fr.REFUNDED_CASH,
        fr.REVERSED_CHARGE,
        fr.ACCOUNT_CREDIT,
        fr.NET_LOSS

    FROM MODELLED.FACT_RETURNS fr

    LEFT JOIN MODELLED.DIM_DATE dd
        ON fr.DATE_KEY = dd.D_DATE_SK
),

MATCHED_RETURNS AS (
    SELECT
        rb.RETURN_NUMBER,
        rb.CUSTOMER_KEY,
        rb.PRODUCT_KEY,

        rb.STORE_KEY AS RETURN_STORE_KEY,
        rb.REASON_KEY,
        rb.RETURN_CHANNEL,

        rb.RETURN_DATE_KEY,
        rb.RETURN_DATE,

        rb.RETURN_QUANTITY,
        rb.RETURN_AMT,
        rb.RETURN_TAX,
        rb.RETURN_AMT_INC_TAX,
        rb.FEE,
        rb.RETURN_SHIP_COST,
        rb.REFUNDED_CASH,
        rb.REVERSED_CHARGE,
        rb.ACCOUNT_CREDIT,
        rb.NET_LOSS,

        sb.ORDER_NUMBER AS MATCHED_ORDER_NUMBER,
        sb.SALE_DATE_KEY,
        sb.SALE_DATE,

        CASE
            WHEN sb.ORDER_NUMBER IS NOT NULL
            THEN DATEDIFF(DAY, sb.SALE_DATE, rb.RETURN_DATE)
            ELSE NULL
        END AS DAYS_TO_RETURN,

        CASE
            WHEN sb.ORDER_NUMBER IS NOT NULL THEN 'Matched'
            ELSE 'Unmatched'
        END AS RETURN_MATCH_STATUS

    FROM RETURNS_BASE rb

    LEFT JOIN SALES_BASE sb
        ON rb.RETURN_NUMBER = sb.ORDER_NUMBER
       AND rb.CUSTOMER_KEY = sb.CUSTOMER_KEY
       AND rb.PRODUCT_KEY = sb.PRODUCT_KEY
),

SALES_AGG AS (
    SELECT
        CUSTOMER_KEY,

        COUNT(DISTINCT ORDER_NUMBER) AS TOTAL_ORDERS,

        SUM(SALES_VALUE) AS TOTAL_SALES_VALUE,

        SUM(SALES_QUANTITY) AS TOTAL_SALES_QUANTITY

    FROM SALES_BASE

    GROUP BY
        CUSTOMER_KEY
),

RETURNS_AGG AS (
    SELECT
        CUSTOMER_KEY,

        COUNT(DISTINCT RETURN_NUMBER) AS RETURN_FREQUENCY,

        COUNT(*) AS RETURN_LINE_COUNT,

        SUM(RETURN_QUANTITY) AS TOTAL_RETURN_QUANTITY,

        SUM(RETURN_AMT) AS RETURN_VALUE,

        SUM(RETURN_AMT_INC_TAX) AS RETURN_VALUE_INC_TAX,

        SUM(FEE) AS TOTAL_RETURN_FEES,

        SUM(RETURN_SHIP_COST) AS TOTAL_RETURN_SHIP_COST,

        SUM(REFUNDED_CASH) AS TOTAL_REFUNDED_CASH,

        SUM(REVERSED_CHARGE) AS TOTAL_REVERSED_CHARGE,

        SUM(ACCOUNT_CREDIT) AS TOTAL_ACCOUNT_CREDIT,

        SUM(NET_LOSS) AS TOTAL_NET_LOSS,

        COUNT(CASE
            WHEN RETURN_MATCH_STATUS = 'Matched' THEN 1
        END) AS MATCHED_RETURN_LINES,

        COUNT(CASE
            WHEN RETURN_MATCH_STATUS = 'Unmatched' THEN 1
        END) AS UNMATCHED_RETURN_LINES,

        COUNT(DISTINCT CASE
            WHEN RETURN_MATCH_STATUS = 'Matched'
            THEN MATCHED_ORDER_NUMBER
        END) AS MATCHED_RETURNED_ORDERS,

        AVG(DAYS_TO_RETURN) AS AVG_DAYS_TO_RETURN,

        MIN(DAYS_TO_RETURN) AS MIN_DAYS_TO_RETURN,

        MAX(DAYS_TO_RETURN) AS MAX_DAYS_TO_RETURN

    FROM MATCHED_RETURNS

    GROUP BY
        CUSTOMER_KEY
)

SELECT
    dc.C_CUSTOMER_SK AS CUSTOMER_KEY,
    dc.C_CUSTOMER_ID AS CUSTOMER_ID,

    CONCAT(
        COALESCE(dc.C_FIRST_NAME, ''),
        ' ',
        COALESCE(dc.C_LAST_NAME, '')
    ) AS CUSTOMER_NAME,

    dc.C_EMAIL_ADDRESS,
    dc.AGE_GROUP,
    dc.CD_GENDER,
    dc.CD_MARITAL_STATUS,
    dc.CD_CREDIT_RATING,
    dc.INCOME_BAND,
    dc.CA_CITY,
    dc.CA_STATE,
    dc.CA_COUNTRY,

    COALESCE(sa.TOTAL_ORDERS, 0) AS TOTAL_ORDERS,

    COALESCE(ra.RETURN_FREQUENCY, 0) AS RETURN_FREQUENCY,

    COALESCE(ra.RETURN_LINE_COUNT, 0) AS RETURN_LINE_COUNT,

    COALESCE(ra.RETURN_FREQUENCY, 0)
        / NULLIF(COALESCE(sa.TOTAL_ORDERS, 0), 0) AS RETURN_PERCENTAGE,

    COALESCE(ra.RETURN_VALUE, 0) AS RETURN_VALUE,

    COALESCE(ra.RETURN_VALUE_INC_TAX, 0) AS RETURN_VALUE_INC_TAX,

    COALESCE(ra.TOTAL_RETURN_QUANTITY, 0) AS TOTAL_RETURN_QUANTITY,

    COALESCE(ra.TOTAL_RETURN_FEES, 0) AS TOTAL_RETURN_FEES,

    COALESCE(ra.TOTAL_RETURN_SHIP_COST, 0) AS TOTAL_RETURN_SHIP_COST,

    COALESCE(ra.TOTAL_REFUNDED_CASH, 0) AS TOTAL_REFUNDED_CASH,

    COALESCE(ra.TOTAL_REVERSED_CHARGE, 0) AS TOTAL_REVERSED_CHARGE,

    COALESCE(ra.TOTAL_ACCOUNT_CREDIT, 0) AS TOTAL_ACCOUNT_CREDIT,

    COALESCE(ra.TOTAL_NET_LOSS, 0) AS TOTAL_NET_LOSS,

    COALESCE(sa.TOTAL_SALES_VALUE, 0) AS TOTAL_SALES_VALUE,

    COALESCE(ra.RETURN_VALUE, 0)
        / NULLIF(COALESCE(sa.TOTAL_SALES_VALUE, 0), 0) AS RETURN_VALUE_RATE,

    ra.AVG_DAYS_TO_RETURN,

    ra.MIN_DAYS_TO_RETURN,

    ra.MAX_DAYS_TO_RETURN,

    COALESCE(ra.MATCHED_RETURN_LINES, 0) AS MATCHED_RETURN_LINES,

    COALESCE(ra.UNMATCHED_RETURN_LINES, 0) AS UNMATCHED_RETURN_LINES,

    COALESCE(ra.MATCHED_RETURNED_ORDERS, 0) AS MATCHED_RETURNED_ORDERS,

    COALESCE(ra.MATCHED_RETURN_LINES, 0)
        / NULLIF(COALESCE(ra.RETURN_LINE_COUNT, 0), 0) AS RETURN_MATCH_RATE,

    CASE
        WHEN COALESCE(ra.RETURN_FREQUENCY, 0) = 0 THEN 'No Returns'

        WHEN COALESCE(ra.RETURN_FREQUENCY, 0)
             / NULLIF(COALESCE(sa.TOTAL_ORDERS, 0), 0) >= 0.50
        THEN 'High Return Behaviour'

        WHEN COALESCE(ra.RETURN_FREQUENCY, 0)
             / NULLIF(COALESCE(sa.TOTAL_ORDERS, 0), 0) >= 0.20
        THEN 'Medium Return Behaviour'

        ELSE 'Low Return Behaviour'
    END AS RETURN_BEHAVIOUR_SEGMENT,

    CURRENT_TIMESTAMP() AS REFRESH_TIMESTAMP

FROM MODELLED.DIM_CUSTOMER dc

LEFT JOIN SALES_AGG sa
    ON dc.C_CUSTOMER_SK = sa.CUSTOMER_KEY

LEFT JOIN RETURNS_AGG ra
    ON dc.C_CUSTOMER_SK = ra.CUSTOMER_KEY;

-- Data Product 4 Customer Value Segmentation

CREATE OR REPLACE TABLE CONSUMER.CUSTOMER_SEGMENTATION AS

WITH SPEND_RANKS AS (

    SELECT
        c.*,

        NTILE(100) OVER (
            ORDER BY LIFETIME_SPEND DESC
        ) AS SPEND_RANK_BUCKET

    FROM CONSUMER.CUSTOMER_360 c

)

SELECT

    CUSTOMER_KEY,
    CUSTOMER_ID,
    CUSTOMER_NAME,

    LIFETIME_SPEND,
    PURCHASE_FREQUENCY,
    RECENCY_DAYS,

    CASE
        WHEN SPEND_RANK_BUCKET <= 5
            THEN 'Platinum'
        WHEN SPEND_RANK_BUCKET <= 20
            THEN 'Gold'
        WHEN SPEND_RANK_BUCKET <= 50
            THEN 'Silver'
        WHEN LIFETIME_SPEND > 0
            THEN 'Bronze'
        ELSE 'No Purchase'
    END AS CUSTOMER_VALUE_SEGMENT

FROM SPEND_RANKS;
