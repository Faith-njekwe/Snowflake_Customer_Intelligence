CREATE OR REPLACE TABLE CONSUMER.REGION_STORE_PERFORMANCE AS

WITH SALES_AGG AS (
    SELECT
        STORE_KEY,
        COUNT(DISTINCT ORDER_NUMBER) AS TOTAL_ORDERS,
        COUNT(DISTINCT CUSTOMER_KEY) AS CUSTOMER_COUNT,
        SUM(NET_PAID) AS TOTAL_SALES,
        SUM(NET_PROFIT) AS TOTAL_PROFIT,
        SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD,
        AVG(NET_PAID) AS AVG_LINE_VALUE,
        SUM(NET_PAID)
            / NULLIF(COUNT(DISTINCT ORDER_NUMBER), 0)
            AS AVG_ORDER_VALUE
    FROM MODELLED.FACT_SALES
    GROUP BY STORE_KEY
),

RETURNS_AGG AS (
    SELECT
        STORE_KEY,
        COUNT(DISTINCT RETURN_NUMBER) AS RETURN_COUNT,
        SUM(RETURN_AMT) AS RETURN_VALUE,
        SUM(RETURN_QUANTITY) AS RETURN_QUANTITY
    FROM MODELLED.FACT_RETURNS
    GROUP BY STORE_KEY
)

SELECT
    ds.STORE_KEY,
    ds.STORE_ID,
    ds.STORE_NAME,
    ds.STORE_MANAGER,

    COALESCE(dr.REGION, 'UNKNOWN') AS REGION,
    COALESCE(dr.COUNTRY, 'United States') AS COUNTRY,
    COALESCE(dr.STATE, 'UNKNOWN') AS STATE,
    COALESCE(dr.COUNTY, 'UNKNOWN') AS COUNTY,

    ds.STORE_SIZE,
    ds.FLOOR_SPACE_CATEGORY,
    ds.EMPLOYEE_COUNT,
    ds.FLOOR_SPACE_SQFT,
    ds.STORE_AGE_YEARS,

    COALESCE(sa.TOTAL_ORDERS, 0) AS TOTAL_ORDERS,
    COALESCE(sa.CUSTOMER_COUNT, 0) AS CUSTOMER_COUNT,
    COALESCE(sa.TOTAL_SALES, 0) AS TOTAL_SALES,
    COALESCE(sa.TOTAL_PROFIT, 0) AS TOTAL_PROFIT,
    COALESCE(sa.TOTAL_QUANTITY_SOLD, 0) AS TOTAL_QUANTITY_SOLD,
    COALESCE(sa.AVG_ORDER_VALUE, 0) AS AVG_ORDER_VALUE,

    COALESCE(ra.RETURN_COUNT, 0) AS RETURN_COUNT,
    COALESCE(ra.RETURN_VALUE, 0) AS RETURN_VALUE,
    COALESCE(ra.RETURN_QUANTITY, 0) AS RETURN_QUANTITY,

    COALESCE(ra.RETURN_COUNT, 0)
        / NULLIF(COALESCE(sa.TOTAL_ORDERS, 0), 0)
        AS RETURN_RATE,

    COALESCE(sa.TOTAL_SALES, 0)
        / NULLIF(ds.EMPLOYEE_COUNT, 0)
        AS SALES_PER_EMPLOYEE,

    COALESCE(sa.TOTAL_PROFIT, 0)
        / NULLIF(ds.EMPLOYEE_COUNT, 0)
        AS PROFIT_PER_EMPLOYEE,

    COALESCE(sa.TOTAL_SALES, 0)
        / NULLIF(ds.FLOOR_SPACE_SQFT, 0)
        AS SALES_PER_SQFT,

    CURRENT_TIMESTAMP() AS REFRESH_TIMESTAMP

FROM MODELLED.DIM_STORE ds

LEFT JOIN MODELLED.DIM_REGION dr
    ON COALESCE(ds.COUNTRY, 'United States') = dr.COUNTRY
   AND COALESCE(ds.STATE, 'UNKNOWN') = dr.STATE
   AND COALESCE(ds.COUNTY, 'UNKNOWN') = dr.COUNTY

LEFT JOIN SALES_AGG sa
    ON ds.STORE_KEY = sa.STORE_KEY

LEFT JOIN RETURNS_AGG ra
    ON ds.STORE_KEY = ra.STORE_KEY;

-- product performance for perfomance info

CREATE OR REPLACE TABLE CONSUMER.PRODUCT_PERFORMANCE AS

WITH SALES_AGG AS (
    SELECT
        fs.PRODUCT_KEY,
        COUNT(DISTINCT fs.ORDER_NUMBER) AS ORDERS_CONTAINING_PRODUCT,
        SUM(fs.QUANTITY) AS TOTAL_UNITS_SOLD,
        SUM(fs.NET_PAID) AS TOTAL_REVENUE,
        SUM(fs.NET_PROFIT) AS TOTAL_PROFIT
    FROM MODELLED.FACT_SALES fs
    GROUP BY fs.PRODUCT_KEY
),

RETURNS_AGG AS (
    SELECT
        fr.PRODUCT_KEY,
        COUNT(DISTINCT fr.RETURN_NUMBER) AS RETURN_COUNT,
        SUM(fr.RETURN_QUANTITY) AS RETURNED_UNITS,
        SUM(fr.RETURN_AMT) AS RETURN_VALUE
    FROM MODELLED.FACT_RETURNS fr
    GROUP BY fr.PRODUCT_KEY
)

SELECT
    dp.ITEM_SK AS PRODUCT_KEY,
    dp.ITEM_ID,
    dp.PRODUCT_NAME,
    dp.CATEGORY,
    dp.CLASS,
    dp.BRAND,
    dp.CURRENT_PRICE,
    dp.WHOLESALE_COST,

    COALESCE(sa.TOTAL_UNITS_SOLD, 0) AS TOTAL_UNITS_SOLD,
    COALESCE(sa.ORDERS_CONTAINING_PRODUCT, 0) AS ORDERS_CONTAINING_PRODUCT,
    COALESCE(sa.TOTAL_REVENUE, 0) AS TOTAL_REVENUE,
    COALESCE(sa.TOTAL_PROFIT, 0) AS TOTAL_PROFIT,

    COALESCE(sa.TOTAL_PROFIT, 0)
        / NULLIF(COALESCE(sa.TOTAL_REVENUE, 0), 0) AS PROFIT_MARGIN,

    -- return transactions
    COALESCE(ra.RETURN_COUNT, 0) AS RETURN_COUNT,
    -- returned units
    COALESCE(ra.RETURNED_UNITS, 0) AS RETURNED_UNITS,
    COALESCE(ra.RETURN_VALUE, 0) AS RETURN_VALUE,

    COALESCE(ra.RETURNED_UNITS, 0)
        / NULLIF(COALESCE(sa.TOTAL_UNITS_SOLD, 0), 0) AS RETURN_RATE,

    CURRENT_TIMESTAMP() AS REFRESH_TIMESTAMP

FROM MODELLED.DIM_PRODUCT dp

LEFT JOIN SALES_AGG sa
    ON dp.ITEM_SK = sa.PRODUCT_KEY

LEFT JOIN RETURNS_AGG ra
    ON dp.ITEM_SK = ra.PRODUCT_KEY;

