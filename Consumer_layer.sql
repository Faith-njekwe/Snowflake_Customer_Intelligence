/*
This creates one row per customer with:

Lifetime Spend
Average Order Value
Purchase Frequency
Recency
Return Rate
Promotion Response
Customer Segment
*/

CREATE OR REPLACE TABLE CONSUMER.CUSTOMER_360 AS

WITH SALES_AGG AS (
    SELECT
        fs.CUSTOMER_KEY,

        COUNT(DISTINCT fs.ORDER_NUMBER) AS TOTAL_ORDERS,

        SUM(fs.NET_PAID) AS LIFETIME_SPEND,

        SUM(fs.NET_PROFIT) AS LIFETIME_PROFIT,

        SUM(fs.QUANTITY) AS TOTAL_ITEMS_PURCHASED,

        SUM(fs.EXT_DISCOUNT_AMT) AS TOTAL_DISCOUNT_AMOUNT,

        SUM(fs.COUPON_AMT) AS TOTAL_COUPON_AMOUNT,

        AVG(fs.NET_PAID) AS AVG_LINE_VALUE,

        SUM(fs.NET_PAID)
            / NULLIF(COUNT(DISTINCT fs.ORDER_NUMBER), 0) AS AVERAGE_ORDER_VALUE,

        COUNT(DISTINCT fs.ORDER_NUMBER) AS PURCHASE_FREQUENCY,

        MAX(dd.D_DATE) AS LAST_PURCHASE_DATE,

        DATEDIFF(
            DAY,
            MAX(dd.D_DATE),
            CURRENT_DATE()
        ) AS RECENCY_DAYS,

        COUNT(DISTINCT CASE
            WHEN fs.PROMOTION_KEY IS NOT NULL THEN fs.ORDER_NUMBER
        END) AS PROMOTION_ORDERS,

        COUNT(DISTINCT CASE
            WHEN fs.PROMOTION_KEY IS NOT NULL THEN fs.ORDER_NUMBER
        END)
            / NULLIF(COUNT(DISTINCT fs.ORDER_NUMBER), 0) AS PROMOTION_RESPONSE_RATE

    FROM MODELLED.FACT_SALES fs

    LEFT JOIN MODELLED.DIM_DATE dd
        ON fs.DATE_KEY = dd.D_DATE_SK

    GROUP BY
        fs.CUSTOMER_KEY
),

RETURNS_AGG AS (
    SELECT
        fr.CUSTOMER_KEY,

        COUNT(DISTINCT fr.RETURN_NUMBER) AS TOTAL_RETURNS,

        SUM(fr.RETURN_AMT) AS TOTAL_RETURN_AMOUNT,

        SUM(fr.RETURN_QUANTITY) AS TOTAL_RETURN_QUANTITY

    FROM MODELLED.FACT_RETURNS fr

    GROUP BY
        fr.CUSTOMER_KEY
),

CUSTOMER_ACTIVITY_AGG AS (
    SELECT
        fca.CUSTOMER_KEY,

        SUM(fca.ORDER_COUNT) AS ACTIVITY_ORDER_COUNT,

        SUM(fca.TOTAL_SPEND) AS ACTIVITY_TOTAL_SPEND,

        SUM(fca.TOTAL_PROFIT) AS ACTIVITY_TOTAL_PROFIT,

        SUM(fca.RETURN_COUNT) AS ACTIVITY_RETURN_COUNT,

        SUM(fca.RETURN_AMOUNT) AS ACTIVITY_RETURN_AMOUNT,

        SUM(fca.NET_SPEND) AS ACTIVITY_NET_SPEND

    FROM MODELLED.FACT_CUSTOMER_ACTIVITY fca

    GROUP BY
        fca.CUSTOMER_KEY
)

SELECT
    dc.C_CUSTOMER_SK AS CUSTOMER_KEY,
    dc.C_CUSTOMER_ID AS CUSTOMER_ID,

    CONCAT(
        COALESCE(dc.C_FIRST_NAME, ''),
        ' ',
        COALESCE(dc.C_LAST_NAME, '')
    ) AS CUSTOMER_NAME,

    dc.C_EMAIL_ADDRESS,
    dc.CUSTOMER_AGE,
    dc.AGE_GROUP,
    dc.CD_GENDER,
    dc.CD_MARITAL_STATUS,
    dc.CD_EDUCATION_STATUS,
    dc.CD_CREDIT_RATING,
    dc.INCOME_BAND,
    dc.HD_BUY_POTENTIAL,
    dc.CA_CITY,
    dc.CA_STATE,
    dc.CA_COUNTRY,

    COALESCE(sa.TOTAL_ORDERS, 0) AS TOTAL_ORDERS,
    COALESCE(sa.LIFETIME_SPEND, 0) AS LIFETIME_SPEND,
    COALESCE(sa.LIFETIME_PROFIT, 0) AS LIFETIME_PROFIT,
    COALESCE(sa.TOTAL_ITEMS_PURCHASED, 0) AS TOTAL_ITEMS_PURCHASED,
    COALESCE(sa.TOTAL_DISCOUNT_AMOUNT, 0) AS TOTAL_DISCOUNT_AMOUNT,
    COALESCE(sa.TOTAL_COUPON_AMOUNT, 0) AS TOTAL_COUPON_AMOUNT,

    COALESCE(sa.AVERAGE_ORDER_VALUE, 0) AS AVERAGE_ORDER_VALUE,

    COALESCE(sa.PURCHASE_FREQUENCY, 0) AS PURCHASE_FREQUENCY,

    sa.LAST_PURCHASE_DATE,

    sa.RECENCY_DAYS,

    COALESCE(ra.TOTAL_RETURNS, 0) AS TOTAL_RETURNS,
    COALESCE(ra.TOTAL_RETURN_AMOUNT, 0) AS TOTAL_RETURN_AMOUNT,
    COALESCE(ra.TOTAL_RETURN_QUANTITY, 0) AS TOTAL_RETURN_QUANTITY,

    COALESCE(ra.TOTAL_RETURNS, 0)
        / NULLIF(COALESCE(sa.TOTAL_ORDERS, 0), 0) AS RETURN_RATE,

    COALESCE(sa.PROMOTION_ORDERS, 0) AS PROMOTION_ORDERS,

    COALESCE(sa.PROMOTION_RESPONSE_RATE, 0) AS PROMOTION_RESPONSE_RATE,

    COALESCE(caa.ACTIVITY_ORDER_COUNT, 0) AS ACTIVITY_ORDER_COUNT,
    COALESCE(caa.ACTIVITY_TOTAL_SPEND, 0) AS ACTIVITY_TOTAL_SPEND,
    COALESCE(caa.ACTIVITY_TOTAL_PROFIT, 0) AS ACTIVITY_TOTAL_PROFIT,
    COALESCE(caa.ACTIVITY_RETURN_COUNT, 0) AS ACTIVITY_RETURN_COUNT,
    COALESCE(caa.ACTIVITY_RETURN_AMOUNT, 0) AS ACTIVITY_RETURN_AMOUNT,
    COALESCE(caa.ACTIVITY_NET_SPEND, 0) AS ACTIVITY_NET_SPEND,
    CURRENT_TIMESTAMP() AS REFRESH_TIMESTAMP

FROM MODELLED.DIM_CUSTOMER dc

LEFT JOIN SALES_AGG sa
    ON dc.C_CUSTOMER_SK = sa.CUSTOMER_KEY

LEFT JOIN RETURNS_AGG ra
    ON dc.C_CUSTOMER_SK = ra.CUSTOMER_KEY

LEFT JOIN CUSTOMER_ACTIVITY_AGG caa
    ON dc.C_CUSTOMER_SK = caa.CUSTOMER_KEY;

